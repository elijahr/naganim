_PYTHON_PASSTHROUGH_TYPES: frozenset[str] = frozenset(
    {
        "int",
        "float",
        "bool",
        "str",
        "bytes",
        "memoryview",
        "None",
        "Any",
    }
)


def parse_c_type_expr(c_type_str: str) -> TypeExpr:
    """Convert a C type declaration string into a `headerkit.ir.TypeExpr` AST node."""
    s = c_type_str.strip()
    if not s:
        return CType(name="void")

    # Handle function pointer syntax: `ret (*)(params...)`
    if "(*)" in s:
        ret_part, rest = s.split("(*)", 1)
        ret_expr = parse_c_type_expr(ret_part.strip())
        rest = rest.strip()
        params_list: list[Parameter] = []
        if rest.startswith("(") and rest.endswith(")"):
            inner = rest[1:-1].strip()
            if inner and inner != "void":
                for p_str in inner.split(","):
                    params_list.append(Parameter(name=None, type=parse_c_type_expr(p_str.strip())))
        return Pointer(pointee=FunctionPointer(return_type=ret_expr, parameters=params_list))

    ptr_depth = 0
    while s.endswith("*"):
        ptr_depth += 1
        s = s[:-1].strip()

    qualifiers: list[str] = []
    tokens = s.split()
    while tokens and tokens[0] in ("const", "volatile", "restrict"):
        qualifiers.append(tokens.pop(0))

    base_name = " ".join(tokens) if tokens else "void"
    expr: TypeExpr = CType(name=base_name, qualifiers=qualifiers)
    for _ in range(ptr_depth):
        expr = Pointer(pointee=expr)
    return expr


class NaganimPyiWriter(PyiWriter):
    """HeaderKit `PyiWriter` specialized for `naganim` rich Python/Nim type annotations."""

    name = "naganim-pyi"
    format_description = "PEP 484 Python type stub (.pyi) declarations for naganim modules"

    def _format_type(self, type_expr: TypeExpr, *, is_param: bool = False) -> str:
        if isinstance(type_expr, CType) and not type_expr.qualifiers:
            raw = type_expr.name.strip()
            if (
                raw in _PYTHON_PASSTHROUGH_TYPES
                or raw.startswith(("list[", "dict[", "tuple[", "set["))
                or " | " in raw
            ) and self._is_valid_python_expr(raw):
                if "Any" in raw:
                    self._needs_any = True
                return raw
        return super()._format_type(type_expr, is_param=is_param)

    def _render(self, unit: SourceUnit | Header) -> str:
        rendered = super()._render(unit)
        # Ensure `from __future__ import annotations` is present right after header comment
        lines = rendered.splitlines()
        if lines and lines[0].startswith("# Auto-generated by headerkit"):
            if "from __future__ import annotations" not in lines:
                lines.insert(1, "from __future__ import annotations")
            return "\n".join(lines) + "\n"
        return rendered


class NaganimCffiWriter(CffiWriter):
    """HeaderKit `CffiWriter` specialized for `naganim` C-ABI modules."""

    name = "naganim-cffi"
    format_description = "CFFI cdef declarations for naganim C-ABI modules"


@hook("write_code", writer="naganim-pyi", priority=Priority.STANDARD)
def _naganim_pyi_write_hook(
    unit: SourceUnit,
    context: PipelineContext | None = None,
    **kwargs: Any,
) -> str | None:
    _ = context
    writer = NaganimPyiWriter(**kwargs)
    return writer.write(unit)


@hook("get_writer", writer="naganim-pyi", priority=Priority.STANDARD)
def _naganim_pyi_get_writer_hook(
    context: PipelineContext | None = None,
    **kwargs: Any,
) -> WriterBackend:
    _ = context
    return NaganimPyiWriter(**kwargs)


