@dataclass(frozen=True)
class NaganimParamSpec:
    name: str
    nim_type: str
    c_type: str
    py_type: str


@dataclass(frozen=True)
class NaganimFunctionSpec:
    name: str
    c_symbol: str
    py_symbol: str
    doc: str
    has_c_abi: bool
    return_nim_type: str
    return_c_type: str
    return_py_type: str
    params: list[NaganimParamSpec] = field(default_factory=list)


@dataclass(frozen=True)
class NaganimModuleIr:
    module: str
    functions: list[NaganimFunctionSpec] = field(default_factory=list)

    @classmethod
    def from_dict(cls, raw: dict[str, Any]) -> NaganimModuleIr:
        funcs: list[NaganimFunctionSpec] = []
        for fn in raw.get("functions", []):
            params = [
                NaganimParamSpec(
                    name=str(p["name"]),
                    nim_type=str(p["nim_type"]),
                    c_type=str(p["c_type"]),
                    py_type=str(p["py_type"]),
                )
                for p in fn.get("params", [])
            ]
            funcs.append(
                NaganimFunctionSpec(
                    name=str(fn["name"]),
                    c_symbol=str(fn["c_symbol"]),
                    py_symbol=str(fn["py_symbol"]),
                    doc=str(fn.get("doc", "")),
                    has_c_abi=bool(fn.get("has_c_abi", False)),
                    return_nim_type=str(fn["return_nim_type"]),
                    return_c_type=str(fn["return_c_type"]),
                    return_py_type=str(fn["return_py_type"]),
                    params=params,
                )
            )
        return cls(module=str(raw["module"]), functions=funcs)

    @classmethod
    def from_json(cls, json_str: str) -> NaganimModuleIr:
        return cls.from_dict(json.loads(json_str))


class NaganimWriterPlugin:
    """Generates `.pyi` type stubs and CFFI `cdef` declarations via `headerkit`."""

    BASE_CFFI_CDEF: str = NaganimCffiWriter().write(
        Header(
            path="naganim_runtime.h",
            declarations=_build_base_runtime_declarations(),
        )
    )

    def __init__(
        self,
        ir: NaganimModuleIr,
        *,
        c_header_path: str | Path | None = None,
        c_header_code: str | None = None,
        nim_source_path: str | Path | None = None,
        jsondoc_path: str | Path | None = None,
    ) -> None:
        self.ir = ir
        self.c_header_path = Path(c_header_path) if c_header_path is not None else None
        self.c_header_code = c_header_code
        self.nim_source_path = Path(nim_source_path) if nim_source_path is not None else None
        self.jsondoc_path = Path(jsondoc_path) if jsondoc_path is not None else None

    @classmethod
    def from_ir_file(
        cls,
        path: str | Path,
        *,
        c_header_path: str | Path | None = None,
        nim_source_path: str | Path | None = None,
    ) -> NaganimWriterPlugin:
        text = Path(path).read_text(encoding="utf-8")
        return cls(
            NaganimModuleIr.from_json(text),
            c_header_path=c_header_path,
            nim_source_path=nim_source_path,
        )

    @classmethod
    def from_ir_json(
        cls,
        json_str: str,
        *,
        c_header_path: str | Path | None = None,
        c_header_code: str | None = None,
        nim_source_path: str | Path | None = None,
    ) -> NaganimWriterPlugin:
        return cls(
            NaganimModuleIr.from_json(json_str),
            c_header_path=c_header_path,
            c_header_code=c_header_code,
            nim_source_path=nim_source_path,
        )

    def build_jsondoc_entries(self) -> list[dict[str, Any]]:
        """Convert `NaganimModuleIr` metadata into `NimJsonDocEnricher` entries."""
        entries: list[dict[str, Any]] = []
        for fn in self.ir.functions:
            param_names = [p.name for p in fn.params]
            c_param_names = [*param_names]
            if fn.has_c_abi and fn.return_nim_type != "void" and fn.return_c_type != "void":
                c_param_names.append("out_res")
            entries.append(
                {
                    "name": fn.name,
                    "type": "skProc",
                    "description": fn.doc,
                    "params": param_names,
                }
            )
            if fn.c_symbol:
                entries.append(
                    {
                        "name": fn.c_symbol,
                        "type": "skProc",
                        "description": fn.doc,
                        "params": c_param_names,
                    }
                )
        return entries

    def _clean_and_enrich_unit(self, unit: SourceUnit) -> Header:
        """Apply `NimCleanupTransform` and `NimJsonDocEnricher` via `ChainedFilter`."""
        pipeline = ChainedFilter(
            NimCleanupTransform(),
            NimJsonDocEnricher(
                jsondoc_path=self.jsondoc_path,
                nim_source_path=self.nim_source_path,
                entries=self.build_jsondoc_entries(),
            ),
        )
        enriched = pipeline.transform(unit)
        return Header(path=enriched.path, declarations=list(enriched.declarations))

    def parse_and_clean_c_header(
        self,
        header_code: str | None = None,
        header_path: str | Path | None = None,
    ) -> Header:
        """Parse a Nim `--header` C file with `headerkit`, clean with `NimCleanupTransform`, and enrich with `NimJsonDocEnricher`."""
        resolved_path = Path(header_path) if header_path is not None else self.c_header_path
        code = header_code if header_code is not None else self.c_header_code
        if code is None and resolved_path is not None and resolved_path.is_file():
            code = resolved_path.read_text(encoding="utf-8")
        if not code:
            return Header(path=str(resolved_path or f"{self.ir.module}.h"), declarations=[])

        filename = str(resolved_path.name) if resolved_path is not None else f"{self.ir.module}.h"
        cleanup = NimCleanupTransform()
        base_inc_dirs = [str(resolved_path.parent)] if resolved_path is not None else []
        inc, args, b_opts = cleanup.prepare_parse(code, filename, base_inc_dirs, [])
        parsed = _parse_with_headerkit_backends(
            code,
            filename,
            include_dirs=inc,
            extra_args=args,
            **b_opts,
        )
        return self._clean_and_enrich_unit(parsed)

    def to_pyi_header(self) -> Header:
        """Build a `headerkit.ir.Header` for the Python module interface and run `NimCleanupTransform` + `NimJsonDocEnricher`."""
        decls: list[Any] = []
        for fn in self.ir.functions:
            params = [
                Parameter(
                    name=f"{p.name}_p{idx}",
                    type=CType(name=p.py_type),
                    type_overrides={"pyi": p.py_type},
                )
                for idx, p in enumerate(fn.params)
            ]
            decls.append(
                Function(
                    name=fn.name,
                    return_type=CType(name=fn.return_py_type),
                    parameters=params,
                    type_overrides={"pyi": fn.return_py_type},
                )
            )
        raw_unit = SourceUnit(path=f"{self.ir.module}.h", declarations=decls)
        return self._clean_and_enrich_unit(raw_unit)

    def to_cffi_header(self) -> Header:
        """Build a `headerkit.ir.Header` for the CFFI C-ABI surface and run `NimCleanupTransform` + `NimJsonDocEnricher`."""
        decls: list[Any] = list(_build_base_runtime_declarations())
        known_names: set[str] = {
            getattr(d, "name", "") for d in decls if getattr(d, "name", None)
        }

        proto_lines: list[str] = []
        for fn in self.ir.functions:
            if not fn.has_c_abi:
                continue
            param_decls = [f"{p.c_type} {p.name}_p{idx}" for idx, p in enumerate(fn.params)]
            if fn.return_nim_type != "void" and fn.return_c_type != "void":
                param_decls.append(f"{fn.return_c_type}* out_res")
            params_str = ", ".join(param_decls) if param_decls else "void"
            proto_lines.append(f"int {fn.c_symbol}({params_str});")
            known_names.add(fn.c_symbol)

        decls.extend(_parse_c_function_prototypes(proto_lines, f"{self.ir.module}.h"))

        # Merge any additional exported C functions parsed from `--header`
        if self.c_header_code is not None or (
            self.c_header_path is not None and self.c_header_path.is_file()
        ):
            parsed_hdr = self.parse_and_clean_c_header()
            for d in parsed_hdr.declarations:
                d_name = getattr(d, "name", None)
                if (
                    isinstance(d, Function)
                    and d_name
                    and d_name not in known_names
                    and not d_name.startswith(("PyInit_", "naganim_py_"))
                ):
                    # Convert `PyObject*` return/params out of CFFI ABI if needed
                    decls.append(replace(d))
                    known_names.add(d_name)

        raw_unit = SourceUnit(path=f"{self.ir.module}.h", declarations=decls)
        return self._clean_and_enrich_unit(raw_unit)

    def generate_pyi_stub(self) -> str:
        """Render PEP 484 `.pyi` stub using `headerkit`'s `PyiWriter` (`NaganimPyiWriter`)."""
        header_ir = self.to_pyi_header()
        writer = NaganimPyiWriter()
        return writer.write(header_ir)

    def generate_cffi_cdef(self) -> str:
        """Render CFFI `cdef` declarations using `headerkit`'s `CffiWriter` (`NaganimCffiWriter`)."""
        header_ir = self.to_cffi_header()
        writer = NaganimCffiWriter()
        return writer.write(header_ir)
